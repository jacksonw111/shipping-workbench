import { buildZip } from '../util/zip.js';

function escapeXml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, '');
}

function columnName(index) {
  let name = '';
  let n = index + 1;
  while (n > 0) {
    const rem = (n - 1) % 26;
    name = String.fromCharCode(65 + rem) + name;
    n = Math.floor((n - 1) / 26);
  }
  return name;
}

function cellXml(ref, cell) {
  const red = cell?.red ? ' s="1"' : '';
  const value = cell?.value ?? '';
  if (value === '' || value === null || value === undefined) return `<c r="${ref}"${red}/>`;
  if (typeof value === 'number' && Number.isFinite(value)) return `<c r="${ref}"${red}><v>${value}</v></c>`;
  return `<c r="${ref}" t="inlineStr"${red}><is><t xml:space="preserve">${escapeXml(value)}</t></is></c>`;
}

function sheetXml(sheet) {
  const columns = sheet.columns ?? [];
  const rows = sheet.rows ?? [];
  const cols = columns
    .map((column, index) => `<col min="${index + 1}" max="${index + 1}" width="${column.width ?? 14}" customWidth="1"/>`)
    .join('');
  const headerRow = columns.length
    ? `<row r="1">${columns.map((column, index) => cellXml(`${columnName(index)}1`, { value: column.header })).join('')}</row>`
    : '';
  const body = rows
    .map((row, rowIndex) => {
      const r = rowIndex + 2;
      const cells = row.map((cell, index) => cellXml(`${columnName(index)}${r}`, cell)).join('');
      return `<row r="${r}">${cells}</row>`;
    })
    .join('');
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><cols>${cols}</cols><sheetData>${headerRow}${body}</sheetData></worksheet>`;
}

